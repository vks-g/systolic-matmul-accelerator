#!/usr/bin/env python3
"""Collect ECP5 synthesis logs into a summary CSV and a critical-path note
(issue #75).

Usage: python3 synth/yosys/summarize.py [results/phase2/synth]

Reads <top>_n<N>.yosys.log and <top>_n<N>.timing.json pairs in the output
directory, writes synth_summary.csv (one row per design and array size) and
critical_paths.md (the top critical path per configuration, for the report
discussion). Resource counts come from the last stat block of the yosys log;
Fmax and the critical path come from nextpnr's timing report.
"""

import csv
import json
import re
import sys
from pathlib import Path

CELLS = ["LUT4", "TRELLIS_FF", "MULT18X18D"]


def yosys_cell_counts(log_path):
    text = Path(log_path).read_text()
    marker = text.rfind("Printing statistics.")
    block = text[marker:] if marker != -1 else text
    counts = {}
    for line in block.splitlines():
        m = re.match(r"\s+(\d+)\s+([A-Za-z0-9_]+)\s*$", line)
        if m and m.group(2) in CELLS:
            counts[m.group(2)] = int(m.group(1))
    return counts


def timing_summary(json_path):
    report = json.loads(Path(json_path).read_text())
    clock, fmax = next(iter(report["fmax"].items()))
    achieved = fmax["achieved"]
    constraint = float(fmax["constraint"])
    path = report["critical_paths"][0]["path"]
    start = path[0]["from"]["cell"]
    end = path[-1]["from"]["cell"]
    delay_ns = sum(entry.get("delay", 0.0) for entry in path)
    # Keep only repo RTL locations; the report also annotates the yosys
    # cell-library files, whose absolute paths are machine-specific.
    sources = []
    for entry in path:
        for src in entry.get("sources", []):
            if src.startswith("rtl/") and src not in sources:
                sources.append(src)
    return {
        "achieved": achieved,
        "constraint": constraint,
        "start": start,
        "end": end,
        "delay_ns": delay_ns,
        "sources": sources[:4],
    }


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("results/phase2/synth")
    rows = []
    paths_md = [
        "# Critical paths (ECP5 LFE5U-25F, post-route)",
        "",
        "Top critical path of each configuration from nextpnr's timing report,",
        "for the report discussion (issue #75). Generated by "
        "`synth/yosys/summarize.py`.",
        "",
    ]
    for ylog in sorted(out.glob("*_n*.yosys.log")):
        m = re.fullmatch(r"(.+)_n(\d+)\.yosys\.log", ylog.name)
        if not m:
            continue
        top, n = m.group(1), int(m.group(2))
        timing_json = out / f"{top}_n{n}.timing.json"
        if not timing_json.exists():
            continue
        counts = yosys_cell_counts(ylog)
        timing = timing_summary(timing_json)
        rows.append(
            {
                "design": top,
                "N": n,
                "LUT4": counts.get("LUT4", 0),
                "TRELLIS_FF": counts.get("TRELLIS_FF", 0),
                "MULT18X18D": counts.get("MULT18X18D", 0),
                "fmax_mhz": f"{timing['achieved']:.2f}",
                "clock_constraint_mhz": f"{timing['constraint']:.0f}",
                "timing_met": "yes" if timing["achieved"] >= timing["constraint"] else "no",
            }
        )
        paths_md += [
            f"## {top}, N = {n}",
            "",
            f"- Achieved Fmax: {timing['achieved']:.2f} MHz "
            f"(constraint {timing['constraint']:.0f} MHz)",
            f"- Path: `{timing['start']}` -> `{timing['end']}`, "
            f"{timing['delay_ns']:.2f} ns over {len(timing['sources'])} annotated nets",
            f"- RTL source lines on the path: {', '.join(timing['sources']) or 'n/a'}",
            "",
        ]
    if not rows:
        sys.exit(f"no synthesis logs found in {out}; run make synth first")
    rows.sort(key=lambda r: (r["design"] != "systolic_top", r["N"]))
    with open(out / "synth_summary.csv", "w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0].keys()), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    (out / "critical_paths.md").write_text("\n".join(paths_md))
    print((out / "synth_summary.csv").read_text())


if __name__ == "__main__":
    main()
